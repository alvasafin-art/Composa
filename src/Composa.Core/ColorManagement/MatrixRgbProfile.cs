using System.Buffers.Binary;
using System.Text;
using SkiaSharp;

namespace Composa.ColorManagement;

/// <summary>Original ICC v4 matrix/TRC profile writer. Public colorimetry only; no third-party profile payloads.
/// The PCS and display media white are D50, with the D65-to-D50 Bradford adaptation recorded in chad.</summary>
internal static class MatrixRgbProfile
{
    internal static byte[] Write(string name, SKColorSpaceXyz matrix, SKColorSpaceTransferFn transfer)
    {
        byte[] Tag(string type, Action<BinaryWriter> body)
        {
            using var memory = new MemoryStream(); using var writer = new BinaryWriter(memory, Encoding.ASCII, leaveOpen: true);
            writer.Write(Encoding.ASCII.GetBytes(type)); writer.Write(0); body(writer); return memory.ToArray();
        }
        void U32(BinaryWriter writer, uint value) { Span<byte> b = stackalloc byte[4]; BinaryPrimitives.WriteUInt32BigEndian(b, value); writer.Write(b); }
        void U16(BinaryWriter writer, ushort value) { Span<byte> b = stackalloc byte[2]; BinaryPrimitives.WriteUInt16BigEndian(b, value); writer.Write(b); }
        void Fixed(BinaryWriter writer, double value) => U32(writer, unchecked((uint)(int)Math.Round(value * 65536)));
        byte[] Text(string text) => Tag("mluc", writer =>
        {
            var bytes = Encoding.BigEndianUnicode.GetBytes(text);
            U32(writer, 1); U32(writer, 12); writer.Write("enUS"u8); U32(writer, (uint)bytes.Length); U32(writer, 28); writer.Write(bytes);
        });
        double[] white = [.9642, 1, .8249];
        var coefficients = matrix.Values; // Values are row-major; SKColorSpaceXyz's [x,y] indexer takes column first.
        var trc = Tag("para", writer => { U16(writer, 4); U16(writer, 0); foreach (var v in transfer.Values) Fixed(writer, v); });
        var tags = new List<(string Key, byte[] Data)> { ("desc", Text(name)), ("cprt", Text("Colorimetric profile generated by Composa.")),
            ("wtpt", Tag("XYZ ", w => { foreach (var v in white) Fixed(w, v); })),
            ("chad", Tag("sf32", w => { foreach (var v in new[] { 1.0479298, .02294679, -.05019223, .0296278, .9904345, -.0170738, -.009243, .015055, .751874 }) Fixed(w, v); })) };
        for (var channel = 0; channel < 3; channel++)
        {
            var c = channel;
            tags.Add(($"{"rgb"[c]}XYZ", Tag("XYZ ", writer =>
            {
                for (var row = 0; row < 3; row++)
                {
                    var sum = coefficients[row * 3] + coefficients[row * 3 + 1] + coefficients[row * 3 + 2];
                    Fixed(writer, coefficients[row * 3 + c] * white[row] / sum);
                }
            })));
            tags.Add(($"{"rgb"[c]}TRC", trc));
        }
        using var output = new MemoryStream(); using var binary = new BinaryWriter(output, Encoding.ASCII, leaveOpen: true);
        var header = new byte[128]; "cmpa"u8.CopyTo(header.AsSpan(4)); BinaryPrimitives.WriteUInt32BigEndian(header.AsSpan(8), 0x04300000);
        "mntrRGB XYZ "u8.CopyTo(header.AsSpan(12));
        ushort[] date = [2026, 1, 1, 0, 0, 0]; for (var i = 0; i < date.Length; i++) BinaryPrimitives.WriteUInt16BigEndian(header.AsSpan(24 + i * 2), date[i]);
        "acsp"u8.CopyTo(header.AsSpan(36)); BinaryPrimitives.WriteUInt32BigEndian(header.AsSpan(64), 1);
        for (var i = 0; i < 3; i++) BinaryPrimitives.WriteInt32BigEndian(header.AsSpan(68 + i * 4), (int)Math.Round(white[i] * 65536));
        "cmpa"u8.CopyTo(header.AsSpan(80)); binary.Write(header); U32(binary, (uint)tags.Count);
        var offset = 132 + tags.Count * 12;
        foreach (var (key, data) in tags)
        { binary.Write(Encoding.ASCII.GetBytes(key)); U32(binary, (uint)offset); U32(binary, (uint)data.Length); offset += (data.Length + 3) & ~3; }
        foreach (var (_, data) in tags) { binary.Write(data); while (output.Position % 4 != 0) binary.Write((byte)0); }
        var result = output.ToArray(); BinaryPrimitives.WriteUInt32BigEndian(result, (uint)result.Length); return result;
    }
}
